/**
 * Bundles the canonical Seed into a single source-free artifact.
 *
 * ── Why a bundle and not "just ship the source" ───────────────────────────
 * Running the canonical Seed needs the Payload config, and the config imports
 * every collection, global, field, hook and plugin — which is effectively the
 * whole `src/` tree. So a seed runner that loads TypeScript at runtime means
 * shipping the source tree, a TypeScript loader and the Payload CLI to the
 * VPS. That is exactly the `operations` image this deployment deliberately
 * does not ship: it is a much larger attack surface, and it makes the VPS a
 * place where application source exists and could be edited in place.
 *
 * Bundling collapses all of that into one compiled `.mjs`. The VPS gets a file
 * it can execute and nothing it can edit meaningfully.
 *
 * ── Why `packages: 'external'` ────────────────────────────────────────────
 * Only FIRST-PARTY code is bundled. Dependencies stay external and are resolved
 * at runtime from the Next.js standalone `node_modules` that already ships in
 * the runner image — the same copies of `payload`, `@payloadcms/*` and `sharp`
 * the application itself runs with. Inlining them instead would be both
 * enormous and wrong: native modules cannot be bundled, and the seed must use
 * byte-identical Payload internals to the running application or it would be
 * writing through a different schema implementation than the one that serves
 * the data.
 *
 * The output is written INTO `.next/standalone`, so the existing
 * `COPY --from=builder /app/.next/standalone ./` in the Dockerfile carries it
 * into the runner image with no extra copy step and no extra layer.
 */
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outfile = path.join(repoRoot, '.next/standalone/seed-runner.mjs')

await build({
  entryPoints: [path.join(repoRoot, 'src/seed/one-shot.ts')],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node24',
  // See the header: only the packages the runner image actually ships, and
  // which must not be bundled, are external.
  // Measured against the actual image: `ls /app/node_modules` is exactly
  // @aws-sdk/client-s3, next, pg, react, react-dom and sharp. Only those may be
  // external — `@aws-sdk/s3-request-presigner`, for instance, is NOT traced in,
  // so externalising the whole @aws-sdk scope failed at load. The
  // source-free-seed drill re-checks this by LOADING the artifact inside the
  // real image rather than trusting this list.
  external: [
    'sharp',
    'pg',
    'pg-native',
    'next',
    'react',
    'react-dom',
    '@aws-sdk/client-s3',
  ],
  // The repository's TypeScript path aliases. esbuild does not read tsconfig
  // paths for aliasing bare specifiers, so they are declared explicitly.
  alias: {
    '@payload-config': path.join(repoRoot, 'src/payload.config.ts'),
  },
  // `@/...` maps to `src/...`. Returning a bare path from `onResolve` would
  // SKIP esbuild's own resolution, so `@/fields/link` would be looked up as a
  // literal file with no extension and fail. Delegating back through
  // `build.resolve` keeps extension and directory-index resolution intact.
  plugins: [
    {
      name: 'src-alias',
      setup(pluginBuild) {
        pluginBuild.onResolve({ filter: /^@\// }, async (args) => {
          if (args.pluginData === 'src-alias') return undefined
          const resolved = await pluginBuild.resolve(
            path.join(repoRoot, 'src', args.path.slice(2)),
            {
              kind: args.kind,
              resolveDir: path.join(repoRoot, 'src'),
              pluginData: 'src-alias',
            },
          )
          if (resolved.errors.length > 0) return { errors: resolved.errors }
          return { path: resolved.path, external: resolved.external }
        })
      },
    },
  ],
  // `import.meta.url` is used by the Payload config to locate the migration
  // directory; keeping ESM output means it stays meaningful.
  banner: {
    js: [
      '// Generated by scripts/build-seed-runner.mjs — do not edit.',
      '// ESM output containing bundled CommonJS: several dependencies call',
      '// `require()` for Node builtins, and an ES module has no `require` in',
      '// scope. Without this shim the artifact fails at load with',
      '// `Dynamic require of "events" is not supported` (measured).',
      "import { createRequire as __aauCreateRequire } from 'node:module'",
      "import { fileURLToPath as __aauFileURLToPath } from 'node:url'",
      "import { dirname as __aauDirname } from 'node:path'",
      'const require = __aauCreateRequire(import.meta.url)',
      'const __filename = __aauFileURLToPath(import.meta.url)',
      'const __dirname = __aauDirname(__filename)',
      '',
    ].join('\n'),
  },
  // `next build` statically REPLACES `process.env.NEXT_PUBLIC_*` with literals;
  // esbuild does not, so without this the bundled Payload config would read an
  // undefined origin at runtime and throw, while the application beside it —
  // built from the same source — works. Baking the same value the image was
  // built with keeps the two in step, and is the same semantics Next applies.
  define: {
    'process.env.NEXT_PUBLIC_SERVER_URL': JSON.stringify(
      process.env.NEXT_PUBLIC_SERVER_URL ?? '',
    ),
  },
  logLevel: 'info',
})

console.log(`seed runner bundled -> ${path.relative(repoRoot, outfile)}`)
