/**
 * Bundles the one-shot canonical version backfill into a single source-free
 * artifact, on exactly the same terms as `scripts/build-seed-runner.mjs`.
 *
 * The reasoning is identical and is written out there in full: running anything
 * that needs the Payload config needs effectively the whole `src/` tree, and
 * shipping that tree to the VPS is the `operations` image this deployment
 * deliberately does not ship. Bundling collapses it into one compiled `.mjs`
 * written into `.next/standalone`, which the Dockerfile's existing
 * `COPY --from=builder /app/.next/standalone ./` already carries into the
 * runner image.
 *
 * `packages: 'external'` is likewise deliberate: only first-party code is
 * bundled, so the backfill writes through byte-identical Payload internals to
 * the ones the running application uses. A backfill that ran on a different
 * copy of `@payloadcms/drizzle` would be writing version rows through a
 * different implementation of the schema than the one that reads them.
 */
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outfile = path.join(repoRoot, '.next/standalone/version-backfill-runner.mjs')

await build({
  entryPoints: [path.join(repoRoot, 'src/migration/version-backfill/one-shot.ts')],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node24',
  // The exact set the runner image ships and which must not be bundled — see
  // build-seed-runner.mjs for how this list was measured. The source-free
  // assertions re-check it by LOADING the artifact inside the real image.
  external: [
    'sharp',
    'pg',
    'pg-native',
    'next',
    'react',
    'react-dom',
    '@aws-sdk/client-s3',
  ],
  alias: {
    '@payload-config': path.join(repoRoot, 'src/payload.config.ts'),
  },
  plugins: [
    {
      name: 'src-alias',
      setup(pluginBuild) {
        pluginBuild.onResolve({ filter: /^@\// }, async (args) => {
          if (args.pluginData === 'src-alias') return undefined
          const resolved = await pluginBuild.resolve(
            path.join(repoRoot, 'src', args.path.slice(2)),
            {
              kind: args.kind,
              resolveDir: path.join(repoRoot, 'src'),
              pluginData: 'src-alias',
            },
          )
          if (resolved.errors.length > 0) return { errors: resolved.errors }
          return { path: resolved.path, external: resolved.external }
        })
      },
    },
  ],
  banner: {
    js: [
      '// Generated by scripts/build-version-backfill-runner.mjs — do not edit.',
      '// ESM output containing bundled CommonJS: several dependencies call',
      '// `require()` for Node builtins, and an ES module has no `require` in',
      '// scope.',
      "import { createRequire as __aauCreateRequire } from 'node:module'",
      "import { fileURLToPath as __aauFileURLToPath } from 'node:url'",
      "import { dirname as __aauDirname } from 'node:path'",
      'const require = __aauCreateRequire(import.meta.url)',
      'const __filename = __aauFileURLToPath(import.meta.url)',
      'const __dirname = __aauDirname(__filename)',
      '',
    ].join('\n'),
  },
  define: {
    'process.env.NEXT_PUBLIC_SERVER_URL': JSON.stringify(
      process.env.NEXT_PUBLIC_SERVER_URL ?? '',
    ),
  },
  logLevel: 'info',
})

console.log(`version backfill runner bundled -> ${path.relative(repoRoot, outfile)}`)
